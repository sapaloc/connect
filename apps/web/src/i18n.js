const STORAGE_KEY = 'connect.lang';

/** @returns {'vi' | 'en'} */
export function getLang() {
  const saved = localStorage.getItem(STORAGE_KEY);
  return saved === 'en' || saved === 'vi' ? saved : 'vi';
}

/** @param {string} lang */
export function setLang(lang) {
  localStorage.setItem(STORAGE_KEY, lang === 'en' ? 'en' : 'vi');
}

/**
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 */
export function t(key, params = {}) {
  const template = messages[getLang()][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(params[name] ?? ''));
}

/** @param {unknown} error */
export function errorText(error) {
  const code = /** @type {{ code?: string }} */ (error)?.code ?? 'UNKNOWN';
  const retryAfter = /** @type {{ retryAfter?: number }} */ (error)?.retryAfter ?? 0;
  const key = `err_${code}`;
  const known = key in messages.en;
  return t(known ? key : 'err_UNKNOWN', { minutes: Math.max(1, Math.ceil(retryAfter / 60)) });
}

/** @param {string | Date} value */
export function formatDateTime(value) {
  return new Intl.DateTimeFormat(getLang() === 'vi' ? 'vi-VN' : 'en-GB', {
    dateStyle: 'short',
    timeStyle: 'short',
    timeZone: 'Asia/Ho_Chi_Minh',
  }).format(new Date(value));
}
