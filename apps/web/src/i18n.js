const STORAGE_KEY = 'connect.lang';

/** @returns {'vi' | 'en'} */
export function getLang() {
  const saved = localStorage.getItem(STORAGE_KEY);
  return saved === 'en' || saved === 'vi' ? saved : 'en';
}

/** @param {string} lang */
export function setLang(lang) {
  localStorage.setItem(STORAGE_KEY, lang === 'vi' ? 'vi' : 'en');
}

/**
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 * @param {'vi' | 'en'} [lang] a fixed language, e.g. for the bilingual print poster
 */
export function t(key, params = {}, lang = getLang()) {
  const one = params.count === 1 ? `${key}_one` : '';
  const template = (one && (messages[lang][one] ?? messages.en[one])) || messages[lang][key] || messages.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(params[name] ?? ''));
}

/** @param {unknown} error */
export function errorText(error) {
  const code = /** @type {{ code?: string }} */ (error)?.code ?? 'UNKNOWN';
  const reason = /** @type {{ details?: { reasons?: string[] } }} */ (error)?.details?.reasons?.[0];
  if (reason && `rule_${reason}` in messages.en) return t(`rule_${reason}`);
  const retryAfter = /** @type {{ retryAfter?: number }} */ (error)?.retryAfter ?? 0;
  const key = `err_${code}`;
  const known = key in messages.en;
  return t(known ? key : 'err_UNKNOWN', { minutes: Math.max(1, Math.ceil(retryAfter / 60)) });
}

/** @param {string | Date} value */
export function formatDate(value) {
  return new Intl.DateTimeFormat(getLang() === 'vi' ? 'vi-VN' : 'en-GB', { dateStyle: 'short', timeZone: 'Asia/Ho_Chi_Minh' }).format(
    new Date(value),
  );
}

/**
 * Whole VND for display ("1.250.000 ₫"); amounts stay 4-decimal strings everywhere else.
 * @param {string} amount
 * @param {'vi' | 'en'} [lang]
 */
export function formatVnd(amount, lang = getLang()) {
  return new Intl.NumberFormat(lang === 'vi' ? 'vi-VN' : 'en-US', { style: 'currency', currency: 'VND', maximumFractionDigits: 0 }).format(
    Number(toVnd(amount)),
  );
}

/**
 * A typed whole amount with thousands separators, for VND inputs ("150000" → "150,000" / "150.000").
 * @param {string} value
 */
export function groupDigits(value) {
  const digits = value.replace(/\D/g, '');
  return digits ? Number(digits).toLocaleString(getLang() === 'vi' ? 'vi-VN' : 'en-US') : '';
}

/** @param {string | Date} value */
export function formatDateTime(value) {
  return new Intl.DateTimeFormat(getLang() === 'vi' ? 'vi-VN' : 'en-GB', {
    dateStyle: 'short',
    timeStyle: 'short',
    timeZone: 'Asia/Ho_Chi_Minh',
  }).format(new Date(value));
}
